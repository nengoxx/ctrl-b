// The TEST IMAGE CORPUS (D65 / MEDIA_MANAGER_PLAN §4 — "the dimension reader is fenced by the shared
// fixture corpus"). Run: `node scripts/gen-test-images.mjs`.
//
// The client's header reader (`src/lib/imageProbe.ts`) parses PNG/JPEG/WebP dimensions out of the
// first bytes of a file, exactly as `app/core/media.py#probe_image` does server-side. A parser like
// that cannot be fenced by hand-written byte arrays: the arrays would encode what the AUTHOR believes
// the format looks like, which is precisely the belief under test. So the corpus is REAL files, and
// this script is how they are made — `sharp` (a devDependency the repo already carries) writes them,
// the truncation and lying-extension arms are cuts and copies of those, and only the two arms that
// cannot exist as a real file are crafted (a PNG whose IHDR *claims* 20000×20000, and the HEIC box
// header no free encoder here can produce).
//
// The outputs are COMMITTED (`tests/fixtures/images/`) — they are a few kilobytes in total and a test
// run must not need a build step. This script exists so they are reproducible and so a new arm is
// added HERE rather than by pasting bytes into a test.
//
// The e2e picker fixtures live in the same folder and are generated by the same run: Playwright's
// `setInputFiles` wants a real path on disk, and a second corpus would drift from this one.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import sharp from "sharp";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "tests", "fixtures", "images");
mkdirSync(OUT, { recursive: true });

const write = (name, buf) => {
  writeFileSync(join(OUT, name), buf);
  console.log(`${name.padEnd(28)} ${buf.length} B`);
};

/** A tiny four-quadrant picture — the shape R54 probed the EXIF crop defect with, so an eyeball on a
 *  failing export tells you WHICH quadrant came back. */
const quadrants = (w, h) =>
  sharp({
    create: { width: w, height: h, channels: 3, background: { r: 200, g: 30, b: 30 } },
  })
    .composite([
      {
        input: {
          create: { width: w >> 1, height: h, channels: 3, background: { r: 30, g: 160, b: 60 } },
        },
        left: w >> 1,
        top: 0,
      },
      {
        input: {
          create: {
            width: w,
            height: h >> 1,
            channels: 4,
            background: { r: 40, g: 60, b: 200, alpha: 0.6 },
          },
        },
        left: 0,
        top: h >> 1,
      },
    ])
    .removeAlpha();

const main = async () => {
  // ── the well-formed arms, one per format branch of the reader ───────────────────────────────────
  write("png-2x3.png", await quadrants(2, 3).png().toBuffer());
  write(
    "png-alpha-8x6.png",
    await sharp({
      create: { width: 8, height: 6, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } },
    })
      .png()
      .toBuffer(),
  );
  write("jpeg-5x4.jpg", await quadrants(5, 4).jpeg({ quality: 70 }).toBuffer());
  // PROGRESSIVE: SOF2, and the marker walk has to reach it past the extra tables. A baseline-only
  // corpus would leave the scan loop's whole reason untested.
  write(
    "jpeg-progressive-9x7.jpg",
    await quadrants(9, 7).jpeg({ quality: 70, progressive: true }).toBuffer(),
  );
  // EXIF Orientation=6 (rotate 90° CW): the header says 400×200 while every engine DISPLAYS 200×400.
  // The reader must report the ENCODED size — that is the number the megapixel guard is about — and
  // the e2e uses this same file to prove the canvas re-encode strips the tag.
  write(
    "jpeg-exif-portrait.jpg",
    await quadrants(400, 200)
      // `withMetadata({orientation})` writes the EXIF tag WITHOUT rotating the pixels, which is the
      // whole point — `withExifMerge({IFD0:{Orientation:"6"}})` silently wrote a 1 (verified by
      // reading the tag back), leaving a fixture that proved nothing.
      .withMetadata({ orientation: 6 })
      .jpeg({ quality: 70 })
      .toBuffer(),
  );
  write("webp-lossy-8x6.webp", await quadrants(8, 6).webp({ quality: 70 }).toBuffer());
  write("webp-lossless-8x6.webp", await quadrants(8, 6).webp({ lossless: true }).toBuffer());
  // VP8X — the extended flavour, which keeps the canvas size in a third place again.
  write(
    "webp-alpha-8x6.webp",
    await sharp({
      create: { width: 8, height: 6, channels: 4, background: { r: 10, g: 10, b: 10, alpha: 0.5 } },
    })
      .webp()
      .toBuffer(),
  );
  write("photo-64x48.png", await quadrants(64, 48).png().toBuffer());
  // The E2E's picker file, and the one place a real ENCODE happens in a test. Big enough that the
  // export's own floor (`MIN_OUTPUT_BYTES`) is nowhere near it — a 64px thumbnail can encode to a
  // few dozen bytes, which is indistinguishable from the dead-canvas failure the floor exists for.
  write("photo-320x240.png", await quadrants(320, 240).png().toBuffer());

  // ── the refusal arms: formats this surface does not serve, said by NAME ─────────────────────────
  write("tiff-8x6.tiff", await quadrants(8, 6).tiff().toBuffer());
  write(
    "vector.svg",
    Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="8" height="6"></svg>\n'),
  );
  // HEIC: no free encoder is available in this sharp build, and the arm only needs the ISO-BMFF box
  // header the sniff reads — `....ftypheic` — which is what a real .heic starts with byte for byte.
  const heic = Buffer.concat([
    Buffer.from([0, 0, 0, 0x18]),
    Buffer.from("ftypheic"),
    Buffer.from([0, 0, 0, 0]),
    Buffer.from("heicmif1"),
  ]);
  write("heic-header.heic", heic);

  // ── the malformed arms: truncation and a lying extension ───────────────────────────────────────
  const png = readFileSync(join(OUT, "png-2x3.png"));
  const jpeg = readFileSync(join(OUT, "jpeg-5x4.jpg"));
  // Stops INSIDE the IHDR chunk: the signature is intact, so a signature-only reader would happily
  // report a size from bytes that are not there.
  write("truncated.png", png.subarray(0, 20));
  // The bare SOI+APP0 marker with no frame header at all.
  write("truncated.jpg", jpeg.subarray(0, 12));
  // Real JPEG bytes under a `.png` name — the mount serves the Content-Type the EXTENSION claims, so
  // this is the pair the server answers 415 for and the client must never mint.
  write("lying.png", jpeg);
  write("not-an-image.txt", Buffer.from("ctrl-b\n"));

  // ── the crafted arm: a header that CLAIMS more pixels than any file could hold ──────────────────
  // The megapixel guard exists to refuse a decode before it is attempted, so its fixture must be a
  // small file making a huge claim — which is exactly what a hostile or corrupt header looks like.
  // The IHDR's width/height are big-endian u32 at offsets 16 and 20; the chunk CRC is left stale
  // because neither reader verifies it (nor should they — a CRC pass is not a decode).
  const huge = Buffer.from(png);
  huge.writeUInt32BE(20000, 16);
  huge.writeUInt32BE(20000, 20);
  write("png-claims-20000x20000.png", huge);
};

await main();
